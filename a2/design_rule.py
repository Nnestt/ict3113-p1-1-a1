"""Assignment 2, Step 2: the evidence behind the escalation rule, from the TUNING set only.

    python a2/design_rule.py      # writes a2/design/design_tables.md

Input: the Assignment 1 per-ticket predictions (evaluation/accuracy_results/acc_<model>_*.csv) and the A1
service log (logs/requests.jsonl, for ticket length), restricted to the 88 tuning rows of
a2/split/tuning_rows.csv. assert_tuning_only() stops the script if a test row is ever used. These are design
inputs only; no figure here is a reported result (those come from the test set).

Latency estimates use the brief's formula (small + escalation fraction x large) with the A1 peak-load p50s
measured on the same SUT (results-record.md, Table 1 / A1 slide 9).

Rule: keep the small model's label iff that predicted label was right at least TAU of the time on the tuning set,
over at least MIN_N predictions; otherwise escalate to the large model, whose label is final.
"""
import csv
import glob
import json
import statistics
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "a2"))
import split  # noqa: E402

OUT = ROOT / "a2" / "design" / "design_tables.md"
SMALL, LARGE, PHI = "qwen2.5:1.5b", "qwen2.5:7b", "phi3.5:3.8b"
MODELS = ["qwen2.5:7b", "phi3.5:3.8b", "qwen2.5:1.5b", "llama3.2:1b"]
MIN_N = 4
# A1 POST /tickets p50 at peak load, mean of 3 runs, same SUT (results-record.md Table 1, A1 slide 9)
A1_P50_MS = {"qwen2.5:1.5b": 487, "phi3.5:3.8b": 1431, "qwen2.5:7b": 2109}
TAUS = [0.90, 0.85, 0.80, 0.75, 0.70, 0.65, 0.60, 0.50]
CHOSEN = {"S1": 0.75, "S2": 0.60}
ALTERNATIVE = {"S1 (option a)": 0.70}


def load():
    tune = {r["row"]: r["gold_label"] for r in split.load_tuning()}
    pred, rid = {}, {}
    for path in sorted(glob.glob(str(ROOT / "evaluation" / "accuracy_results" / "acc_*.csv"))):
        with open(path, encoding="utf-8") as f:
            rows = list(csv.DictReader(f))
        model = rows[0]["model"]
        pred[model] = {int(r["row"]): r["predicted"] for r in rows if int(r["row"]) in tune}
        rid[model] = {r["request_id"]: int(r["row"]) for r in rows if int(r["row"]) in tune}
    for model in MODELS:
        split.assert_tuning_only(pred[model])
        assert len(pred[model]) == len(tune), f"{model}: {len(pred[model])} tuning predictions, expected {len(tune)}"
    chars = {}
    with open(ROOT / "logs" / "requests.jsonl", encoding="utf-8") as f:
        for line in f:
            d = json.loads(line)
            for m in MODELS:
                row = rid[m].get(d.get("request_id"))
                if row is not None:
                    chars[row] = d.get("narrative_chars")
    split.assert_tuning_only(chars)
    return tune, pred, chars


def pct(k, n):
    return f"{k}/{n} ({100 * k / n:.1f}%)" if n else "0/0"


def accept_set(tune, small, tau):
    prec = {}
    for label in sorted(set(small.values())):
        rows = [r for r in tune if small[r] == label]
        prec[label] = (sum(tune[r] == label for r in rows), len(rows))
    return {c for c, (k, n) in prec.items() if n >= MIN_N and k / n >= tau}, prec


def evaluate(tune, small, large, accept, cats):
    final = {r: small[r] if small[r] in accept else large[r] for r in tune}
    kept = [r for r in tune if small[r] in accept]
    esc = [r for r in tune if small[r] not in accept]
    per_cat = {c: (sum(final[r] == c for r in tune if tune[r] == c), sum(tune[r] == c for r in tune)) for c in cats}
    return {"correct": sum(final[r] == tune[r] for r in tune), "kept": kept, "esc": esc, "per_cat": per_cat,
            "escaped": [r for r in kept if small[r] != tune[r]],
            "caught": sum(small[r] != tune[r] for r in esc)}


def limits(tune, ref, cats):
    k = sum(ref[r] == tune[r] for r in tune)
    overall = k / len(tune) - 0.10
    per = {c: sum(ref[r] == c for r in tune if tune[r] == c) / sum(tune[r] == c for r in tune) - 0.15 for c in cats}
    return overall, per


def passes(ev, n, lim_overall, lim_cat):
    headroom = {c: (k / m - lim_cat[c]) * m for c, (k, m) in ev["per_cat"].items()}
    ok = ev["correct"] / n >= lim_overall - 1e-9 and min(headroom.values()) >= -1e-9
    worst = min(headroom, key=headroom.get)
    return ok, worst, headroom[worst]


def main():
    tune, pred, chars = load()
    n = len(tune)
    cats = sorted(set(tune.values()))
    small, large, phi = pred[SMALL], pred[LARGE], pred[PHI]
    lim_overall, lim_cat = limits(tune, large, cats)
    r_small, r_phi = A1_P50_MS[SMALL] / A1_P50_MS[LARGE], A1_P50_MS[PHI] / A1_P50_MS[LARGE]
    L = ["# A2 escalation rule: tuning-set evidence", "",
         "Generated by `python a2/design_rule.py` from the A1 per-ticket predictions, **88 tuning rows only** "
         "(`assert_tuning_only` enforced). Design inputs, not reported results.", ""]

    L += ["## 1. Each model alone (tuning set)", "",
          "| Model | Overall | " + " | ".join(cats) + " |", "|---|---|" + "---|" * len(cats)]
    for m in MODELS:
        per = [pct(sum(pred[m][r] == c for r in tune if tune[r] == c), sum(tune[r] == c for r in tune)) for c in cats]
        L.append(f"| {m} | {pct(sum(pred[m][r] == tune[r] for r in tune), n)} | " + " | ".join(per) + " |")
    L += ["", f"Proxy limits from {LARGE} on tuning: overall ≥ {100 * lim_overall:.1f}%; per category ≥ 7b − 15 points "
          "(the real limits come from the test set).", ""]
    ok_phi, worst_phi, h_phi = passes(evaluate(tune, phi, phi, set(), cats), n, lim_overall, lim_cat)
    L += [f"{PHI} alone: {'passes' if ok_phi else 'FAILS'} on tuning; weakest category {worst_phi} "
          f"({h_phi:+.1f} tickets against its limit).", ""]

    accept_any, prec = accept_set(tune, small, 0.0)
    L += [f"## 2. How often each {SMALL} label is right (tuning set)", "",
          f"Precision = of the tickets {SMALL} gave this label, how many really are this category. "
          f"Only labels with at least {MIN_N} predictions can be accepted.", "",
          "| Predicted label | Right / predicted | Precision |", "|---|---|---|"]
    for label, (k, m) in sorted(prec.items(), key=lambda kv: -kv[1][0] / kv[1][1]):
        L.append(f"| {label} | {k}/{m} | {100 * k / m:.0f}%{'' if m >= MIN_N else ' (too few)'} |")
    L.append("")

    L += [f"## 3. The τ sweep: cascade {SMALL} → {LARGE} (minimum {MIN_N} predictions)", "",
          f"Estimated latency = small + f × large (brief formula), using the A1 peak-load p50s on the same SUT "
          f"(results-record.md Table 1: {SMALL} {A1_P50_MS[SMALL]:,} ms, {PHI} {A1_P50_MS[PHI]:,} ms, "
          f"{LARGE} {A1_P50_MS[LARGE]:,} ms; so {SMALL} = {r_small:.2f}× and {PHI} = {r_phi:.2f}× of {LARGE}). "
          f"{LARGE} alone: "
          f"{pct(sum(large[r] == tune[r] for r in tune), n)}.", "",
          "| τ | Accept list | Escalated f | Accuracy | Kept but wrong (escaped) | Limits | Weakest category | Est. latency vs 7b |",
          "|---|---|---|---|---|---|---|---|"]
    names = {v: k for k, v in {**ALTERNATIVE, **CHOSEN}.items()}
    for tau in TAUS:
        accept, _ = accept_set(tune, small, tau)
        ev = evaluate(tune, small, large, accept, cats)
        ok, worst, h = passes(ev, n, lim_overall, lim_cat)
        f = len(ev["esc"]) / n
        tag = f" **{names[tau]}**" if tau in names else ""
        L.append(f"| {tau:.0%}{tag} | {', '.join(sorted(accept)) or '(none)'} | {len(ev['esc'])}/{n} = {f:.0%} | "
                 f"{pct(ev['correct'], n)} | {len(ev['escaped'])} of {len(ev['kept'])} | {'PASS' if ok else 'FAIL'} | "
                 f"{worst} {h:+.1f} | {r_small + f:.2f}× |")
    L += ["", f"Break-even: the cascade beats {LARGE} alone only if f < {1 - r_small:.0%}, and beats {PHI} alone only "
          f"if f < {r_phi - r_small:.0%}.", ""]

    L += ["## 4. The chosen settings in detail", ""]
    for name, tau in {**CHOSEN, **ALTERNATIVE}.items():
        accept, _ = accept_set(tune, small, tau)
        ev = evaluate(tune, small, large, accept, cats)
        escaped = Counter(tune[r] for r in ev["escaped"])
        L += [f"**{name}: τ = {tau:.0%}**, accept {', '.join(sorted(accept))}. Escalated {len(ev['esc'])}/{n}; "
              f"{SMALL} was wrong on {ev['caught']} of those (caught). Kept {len(ev['kept'])}, "
              f"right {len(ev['kept']) - len(ev['escaped'])}, wrong {len(ev['escaped'])} (escaped: "
              f"{', '.join(f'{c} {k}' for c, k in escaped.most_common()) or 'none'}).", "",
              "| Category | Cascade | Limit | Headroom (tickets) |", "|---|---|---|---|"]
        for c in cats:
            k, m = ev["per_cat"][c]
            L.append(f"| {c} | {pct(k, m)} | {100 * lim_cat[c]:.1f}% | {(k / m - lim_cat[c]) * m:+.1f} |")
        L.append("")

    best = None
    for tau in [t / 100 for t in range(0, 101)]:
        accept, _ = accept_set(tune, small, tau)
        ok, _, _ = passes(evaluate(tune, small, phi, accept, cats), n, lim_overall, lim_cat)
        best = best or (tau if ok else None)
    L += [f"## 5. Why not {SMALL} → {PHI}", "",
          f"No τ makes a {SMALL} → {PHI} cascade pass on tuning ({'none found' if best is None else f'first pass at τ={best:.0%}'}): "
          f"{PHI} alone already fails {worst_phi}, and accepting {SMALL}'s answers cannot repair it. "
          f"So the pair is {SMALL} → {LARGE}.", ""]

    right = [chars[r] for r in tune if small[r] == tune[r] and chars.get(r)]
    wrong = [chars[r] for r in tune if small[r] != tune[r] and chars.get(r)]
    L += ["## 6. Why not a length rule (brief method 4)", "",
          f"Median length of tickets {SMALL} got right: {statistics.median(right):.0f} chars; wrong: "
          f"{statistics.median(wrong):.0f} chars. Short tickets are not easier:", "",
          "| Ticket length | Tickets | 1.5b right |", "|---|---|---|"]
    for cut in (400, 600, 800, 1000, 1500):
        rows = [r for r in tune if chars.get(r, 0) <= cut]
        L.append(f"| ≤ {cut} chars | {len(rows)} | {pct(sum(small[r] == tune[r] for r in rows), len(rows))} |")
    L += ["", "## 7. Other methods", "",
          f"- **Agreement (method 2):** the only other small model, llama3.2:1b, is right on "
          f"{pct(sum(pred['llama3.2:1b'][r] == tune[r] for r in tune), n)} of tuning tickets, so agreement with it "
          "carries little signal, and two small calls cost close to one large one.",
          "- **Self-reported confidence (method 3):** needs a second prompt and a second model call on every ticket, "
          "and small models are often confidently wrong.", ""]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()

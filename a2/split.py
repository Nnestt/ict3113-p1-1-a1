"""Assignment 2, Step 1: split the frozen golden set into a tuning set and a test set.

Rule (brief, Step 1): "Sort your golden-set tickets by row number. Odd rows -> tuning
set, even rows -> test set."

Reading used by this team: sort the 175 golden tickets by their `row` ID, number them
by POSITION 1..175, then odd positions -> tuning and even positions -> test.
    position 1 = row 1007 -> tuning
    position 2 = row 1010 -> test
(The row IDs themselves are not used for parity; sorting would be pointless otherwise.)

Usage (from repo root):
    python a2/split.py            # write a2/split/*.csv and split_summary.md
    python a2/split.py --check    # verify committed files still match the golden set

Other A2 scripts import load_tuning(), load_test() and assert_tuning_only() from here.
Design/tuning scripts must call assert_tuning_only(); only the final accuracy scorer
may read the test set.
"""
import argparse
import csv
import sys
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GOLD = ROOT / "golden_set" / "gold_labels.csv"
OUT = ROOT / "a2" / "split"
TUNING = OUT / "tuning_rows.csv"
TEST = OUT / "test_rows.csv"
SUMMARY = OUT / "split_summary.md"


def _read(path):
    with open(path, newline="", encoding="utf-8") as f:
        return [{"row": int(r["row"]), "gold_label": r["gold_label"]} for r in csv.DictReader(f)]


def make_split():
    rows = sorted(_read(GOLD), key=lambda r: r["row"])
    ids = [r["row"] for r in rows]
    if len(ids) != len(set(ids)):
        sys.exit("duplicate row IDs in golden set")
    tuning = [r for pos, r in enumerate(rows, 1) if pos % 2 == 1]
    test = [r for pos, r in enumerate(rows, 1) if pos % 2 == 0]
    return rows, tuning, test


def load_tuning():
    return _read(TUNING)


def load_test():
    return _read(TEST)


def assert_tuning_only(row_ids):
    """Raise if any of row_ids belongs to the test set (guards design scripts)."""
    test_ids = {r["row"] for r in load_test()}
    leaked = sorted(set(int(x) for x in row_ids) & test_ids)
    if leaked:
        raise AssertionError(f"{len(leaked)} test-set rows used in tuning/design: {leaked[:10]}")


def _write_csv(path, rows):
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["row", "gold_label"], lineterminator="\n")
        w.writeheader()
        w.writerows(rows)


def _summary(rows, tuning, test):
    cats = sorted(Counter(r["gold_label"] for r in rows).items(), key=lambda kv: -kv[1])
    ct, cs = Counter(r["gold_label"] for r in tuning), Counter(r["gold_label"] for r in test)
    lines = [
        "# Assignment 2 golden-set split",
        "",
        "Generated by `python a2/split.py`. Do not edit by hand.",
        "",
        "- Source: `golden_set/gold_labels.csv` (frozen in Assignment 1)",
        "- Rule: sort by `row`; number positions 1..N; odd position -> tuning, even position -> test",
        f"- First tuning row: {tuning[0]['row']} (position 1); first test row: {test[0]['row']} (position 2)",
        f"- Totals: golden {len(rows)}, tuning {len(tuning)}, test {len(test)}",
        "",
        "| Category | Golden | Tuning | Test | Test small (n < 10)? |",
        "|---|---:|---:|---:|---|",
    ]
    for c, n in cats:
        lines.append(f"| {c} | {n} | {ct[c]} | {cs[c]} | {'yes - 1 ticket = ' + format(100 / cs[c], '.1f') + ' pp' if cs[c] < 10 else 'no'} |")
    lines.append(f"| **Total** | {len(rows)} | {len(tuning)} | {len(test)} | |")
    lines += [
        "",
        "Use the tuning set only to design the escalation rule and choose its two settings.",
        "Every accuracy figure reported in Assignment 2 comes from the test set.",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="verify committed split files, write nothing")
    args = ap.parse_args()

    rows, tuning, test = make_split()
    assert len(tuning) + len(test) == len(rows)
    assert not {r["row"] for r in tuning} & {r["row"] for r in test}

    if args.check:
        ok = TUNING.exists() and TEST.exists() and load_tuning() == tuning and load_test() == test
        print("split OK" if ok else "split MISMATCH: committed files differ from golden set")
        sys.exit(0 if ok else 1)

    OUT.mkdir(parents=True, exist_ok=True)
    _write_csv(TUNING, tuning)
    _write_csv(TEST, test)
    SUMMARY.write_text(_summary(rows, tuning, test), encoding="utf-8")
    print(f"tuning {len(tuning)} -> {TUNING.relative_to(ROOT)}")
    print(f"test   {len(test)} -> {TEST.relative_to(ROOT)}")
    print(f"summary -> {SUMMARY.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
